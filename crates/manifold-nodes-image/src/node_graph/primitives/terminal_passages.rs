//! Text passages for the Code Terminal panes. Each passage is a short run of
//! lines that reads as one coherent block: a command and its output, one
//! function, a burst of log lines, or a memory view. A screen group shows one
//! passage top to bottom and moves into the next passage when it runs out.
//!
//! Placeholders start with `%` and are filled by `terminal_vocabulary`:
//! `%L %R %B %E` measured left/right/light/edge as 0.00, `%C` contour status,
//! `%H` 8 hex digits, `%h` 4 hex digits, `%b` 2 hex digits, `%G` 7-digit
//! commit hash, `%N` number up to 9999, `%n` one digit, `%P` IPv4 octet fixed
//! for the passage, `%W` a power-of-two size, `%M` milliseconds like 12.4,
//! `%K` a file size, `%T` a clock timestamp, `%S` a sequence number that
//! counts down the passage, `%A` an address that steps 16 bytes per line,
//! `%X` sixteen hex bytes plus their ASCII column, `%D` one x86 instruction,
//! `%%` a literal percent sign.

pub(super) type Passage = &'static [&'static [u8]];

